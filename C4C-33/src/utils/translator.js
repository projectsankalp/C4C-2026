// Translate function
export const t = (key, lang = 'EN') => {
  if (!translations[key]) return key;
  return translations[key][lang] || translations[key]['EN'] || key;
};

// Text-to-Speech function
export const speakText = (text, lang = 'EN', onStart = () => {}, onEnd = () => {}) => {
  if (!window.speechSynthesis) return;
  
  // Cancel previous speech
  window.speechSynthesis.cancel();
  
  const utterance = new SpeechSynthesisUtterance(text);
  
  // Map our language codes to speech synthesis locales
  const localeMap = {
    EN: 'en-US',
    HI: 'hi-IN',
    TA: 'ta-IN',
    BN: 'bn-IN',
    KN: 'kn-IN',
    MR: 'mr-IN',
    TE: 'te-IN'
  };
  
  utterance.lang = localeMap[lang] || 'en-US';
  
  // Find a voice matching the language if possible
  const voices = window.speechSynthesis.getVoices();
  const matchingVoice = voices.find(v => v.lang.startsWith(utterance.lang.substring(0, 2)));
  if (matchingVoice) {
    utterance.voice = matchingVoice;
  }
  
  utterance.rate = 0.95; // Slightly slower for clear accessibility reading
  utterance.onstart = onStart;
  utterance.onend = onEnd;
  utterance.onerror = onEnd;
  
  window.speechSynthesis.speak(utterance);
};

// Field translator helper
export const translateField = (obj, field, lang = 'EN') => {
  if (!obj) return '';
  const key = `${field}_${lang}`;
  return obj[key] || obj[`${field}_EN`] || obj[field] || '';
};

