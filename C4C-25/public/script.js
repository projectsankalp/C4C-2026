let availableVoices = [];
let voiceLoadTimer = null;

function refreshVoices() {
  if (!("speechSynthesis" in window)) return;
  availableVoices = window.speechSynthesis.getVoices();
}

function findVoice(language) {
  refreshVoices();
  const voiceMatchers = {
    kn: (voice) => voice.lang.toLowerCase().startsWith("kn") || /kannada/i.test(voice.name),
    hi: (voice) => voice.lang.toLowerCase().startsWith("hi") || /hindi/i.test(voice.name),
    en: (voice) => voice.lang.toLowerCase().startsWith("en-in") || voice.lang.toLowerCase().startsWith("en")
  };

  const matcher = voiceMatchers[language] || voiceMatchers.en;
  if (language === "kn" || language === "hi") {
    return availableVoices.find(matcher) || null;
  }
  return availableVoices.find(matcher) || availableVoices.find(voiceMatchers.en) || null;
}

function speechLang() {
  if (state.language === "kn") return "kn-IN";
  if (state.language === "hi") return "hi-IN";
  return "en-IN";
}

function speak(message) {
  if (!("speechSynthesis" in window)) return;
  refreshVoices();
  if (!availableVoices.length && !voiceLoadTimer) {
    voiceLoadTimer = window.setTimeout(() => {
      voiceLoadTimer = null;
      speak(message);
    }, 300);
    return;
  }
  window.speechSynthesis.cancel();
  window.speechSynthesis.resume();
  const utterance = new SpeechSynthesisUtterance(message);
  utterance.lang = speechLang();
  utterance.rate = 0.9;
  utterance.pitch = 1;
  const voice = findVoice(state.language);
  if (voice) {
    utterance.voice = voice;
  }
  window.speechSynthesis.speak(utterance);
}

