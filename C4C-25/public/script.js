function watchCurrentPosition() {
  return new Promise((resolve, reject) => {
    let bestPosition = null;
    let settled = false;

    const finish = (callback, value) => {
      if (settled) return;
      settled = true;
      window.clearTimeout(timer);
      navigator.geolocation.clearWatch(watchId);
      callback(value);
    };

    const watchId = navigator.geolocation.watchPosition(
      (position) => {
        if (!bestPosition || position.coords.accuracy < bestPosition.coords.accuracy) {
          bestPosition = position;
        }

        if (position.coords.accuracy <= 250) {
          finish(resolve, position);
        } else {
          locationStatus.textContent = `Finding your current location... accuracy ${Math.round(position.coords.accuracy)}m`;
        }
      },
      (error) => {
        if (bestPosition) {
          finish(resolve, bestPosition);
        } else {
          finish(reject, error);
        }
      },
      { enableHighAccuracy: true, timeout: 30000, maximumAge: 0 }
    );

    const timer = window.setTimeout(() => {
      if (bestPosition) {
        finish(resolve, bestPosition);
      } else {
        finish(reject, new Error("Location timed out"));
      }
    }, 30000);
  });
}

async function resolvePlaceName(latitude, longitude) {
  try {
    const region = await requestJson(`/api/reverse-geocode?lat=${latitude}&lon=${longitude}`, 12000);
    if (region.label) return region.label;
  } catch (error) {
    // Try the nearest-place endpoint next.
  }

  const nearest = await requestJson(`/api/nearest-place?lat=${latitude}&lon=${longitude}`, 12000);
  return nearest.label || "";
}

async function useCoordinates(latitude, longitude, accuracy) {
  state.latitude = latitude;
  state.longitude = longitude;
  let placeName = "";
  try {
    placeName = await resolvePlaceName(latitude, longitude);
  } catch (error) {
    placeName = regionInput.value;
  }

  if (!isGenericPlaceName(placeName)) {
    regionInput.value = placeName;
    locationStatus.textContent = `${t("locationFound")}: ${placeName}${accuracy ? ` (accuracy ${Math.round(accuracy)}m)` : ""}`;
    await loadDestinations(placeName, latitude, longitude);
  } else {
    await useApproximateLocation();
  }
}

async function useApproximateLocation() {
  locationStatus.textContent = t("locationBlocked");
  let location;
  try {
    location = await requestJson("/api/ip-location", 12000);
  } catch (error) {
    location = { label: "", latitude: null, longitude: null };
  }

  if (location.latitude && location.longitude && isGenericPlaceName(location.label)) {
    try {
      location.label = await resolvePlaceName(location.latitude, location.longitude);
    } catch (error) {
      location.label = "";
    }
  }

  if (isGenericPlaceName(location.label)) {
    regionInput.value = "";
    locationStatus.textContent = "Type your area name, then select a nearby destination.";
    await loadDestinations("", location.latitude, location.longitude);
    return;
  }

  regionInput.value = location.label;
  locationStatus.textContent = `Approximate location found: ${location.label}`;
  await loadDestinations(location.label, location.latitude, location.longitude);
}

async function loadDestinations(region, latitude = state.latitude, longitude = state.longitude) {
  destinationStatus.textContent = t("loadingPlaces");
  const params = new URLSearchParams();
  if (region) params.set("region", region);
  if (latitude && longitude) {
    params.set("lat", latitude);
    params.set("lon", longitude);
  }

  try {
    const data = await requestJson(`/api/places?${params.toString()}`, 35000);
    if (!isGenericPlaceName(data.region) && data.region !== region) {
      regionInput.value = data.region;
      locationStatus.textContent = `${t("locationFound")}: ${data.region}`;
    }
    if (data.latitude && data.longitude) {
      state.latitude = data.latitude;
      state.longitude = data.longitude;
    }
    setDestinations(data.places || []);
    destinationStatus.textContent = `${t("placesLoaded")}: ${state.places.length}`;
  } catch (error) {
    let fallbackRegion = region;
    if (isGenericPlaceName(fallbackRegion)) {
      try {
        const location = await requestJson("/api/ip-location", 12000);
        if (!isGenericPlaceName(location.label)) {
          fallbackRegion = location.label;
          regionInput.value = location.label;
          state.latitude = location.latitude || state.latitude;
          state.longitude = location.longitude || state.longitude;
          locationStatus.textContent = `Approximate location found: ${location.label}`;
        }
      } catch (locationError) {
        fallbackRegion = "";
      }
    }
    const offlinePlaces = getOfflinePlaces(fallbackRegion);
    setDestinations(offlinePlaces);
    destinationStatus.textContent = `${t("placesLoaded")}: ${offlinePlaces.length}`;
  }
}

