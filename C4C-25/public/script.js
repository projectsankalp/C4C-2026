function dashboardSignals(air, region) {
  const aqi = Number(air.aqi);
  const numericAqi = Number.isFinite(aqi) ? aqi : 100;
  const safety = Math.max(0, Math.min(100, 100 - Math.round(numericAqi / 3)));
  const risk = numericAqi > 150 ? "HIGH" : numericAqi > 80 ? "MODERATE" : "LOW";
  const crop = numericAqi > 150 ? "HIGH" : numericAqi > 100 ? "MODERATE" : "LOW";
  const traffic = numericAqi > 150 ? "HIGH" : numericAqi > 100 ? "ELEVATED" : "NORMAL";
  const health = numericAqi > 150
    ? ["Reduce outdoor activity", "Children should avoid heavy outdoor travel", "Masks recommended outdoors"]
    : numericAqi > 100
      ? ["Limit long outdoor activity", "Children can travel with caution", "Masks suggested for sensitive groups"]
      : ["Outdoor activity is safe currently", "Children can travel safely", "Masks not required currently"];

  return {
    safety,
    risk,
    crop,
    traffic,
    health,
    alertStatus: air.status === "DATA UNAVAILABLE" || air.status === "OFFLINE ESTIMATE"
      ? "offline"
      : "detected"
  };
}

