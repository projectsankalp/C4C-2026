function isGenericPlaceName(value) {
  return !value || /^current area$/i.test(String(value).trim()) || /^unknown location$/i.test(String(value).trim());
}

function repairTextEncoding(value) {
  if (typeof value !== "string" || !/[ÃÂà]/.test(value)) return value;
  try {
    return decodeURIComponent(escape(value));
  } catch {
    return value;
  }
}

